#!/usr/bin/env python3
"""Bring the JStationX XMB artwork into uscl-shell/xmb/.

All of it is generated by the player's kodi-xmb project (no Sony assets): the silk background layers
(bg_lab.py), Material Icons glyphs with the XMB glow (render_assets.py, Apache-2.0 icons) and the UI pieces
(render_ui.py). This copies what the home screen uses and renders the few icons and avatars USCL adds,
with the same functions so they match.

usage: KODI_XMB=~/src/kodi-xmb python3 -I uscl-shell/tools/xmb_assets.py
"""
import os
import shutil
import sys

KODI = os.path.expanduser(os.environ.get("KODI_XMB", "~/src/kodi-xmb"))
SRC = os.path.join(KODI, "build", "skin", "media", "xmb")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "xmb")

BACKGROUND = ["bg_base.png", "bg_bloom.png", "silk_a.png", "silk_b.png", "silk_c.png",
              "sparkle_a.png", "sparkle_b.png", "halo.png", "clockbox.png", "white.png"]
UI = ["arrow_left.png", "badge_ok.png", "badge_err.png", "badge_count.png", "badge_bolt.png",
      "btn_cross.png", "btn_circle.png", "btn_triangle.png", "btn_square.png", "focus_bar.png",
      "options_panel.png", "setting_dot.png", "button_focus.png", "button_nofocus.png", "status_net.png", "spinner_ring.png", "notify_card.png"] + \
     [f"battery_{i}.png" for i in range(11)]

# Material Icons code points (third_party/MaterialIcons-Regular.codepoints in kodi-xmb)
ICONS = {
    "cat_users": 0xE7FD, "cat_settings": 0xE8B8, "cat_game": 0xEA28, "cat_network": 0xE80B, "cat_friends": 0xE7FB,
    "it_power": 0xE8AC, "it_restart": 0xF053, "it_update": 0xE62A, "it_games": 0xE338, "it_system": 0xE8B9,
    "it_theme": 0xE40A, "it_clock": 0xE192, "it_gamepad": 0xE30F, "it_display": 0xEB97, "it_sound": 0xE050,
    "it_network": 0xEB2F, "it_nettest": 0xE63E, "it_info": 0xE88E, "it_files": 0xE2C7, "it_help": 0xE887,
    "it_addgames": 0xE2CC, "it_host": 0xE7F0, "it_join": 0xEA77, "it_logout": 0xE9BA, "it_tune": 0xE429,
    "it_storage": 0xE1DB, "it_usb": 0xE1E0, "it_person": 0xE7FD, "it_face": 0xE87C, "it_speed": 0xE9E4,
    "it_desktop": 0xE30C, "it_play": 0xE1C4, "it_stream": 0xE308, "it_memory": 0xE322,
}


def main():
    if not os.path.isdir(SRC):
        sys.exit(f"{SRC} not found: build kodi-xmb first (tools/bg_lab.py build2, render_assets.py, render_ui.py)")
    os.makedirs(os.path.join(OUT, "ui"), exist_ok=True)
    for name in BACKGROUND:
        shutil.copy(os.path.join(SRC, name), os.path.join(OUT, name))
    for name in UI:
        shutil.copy(os.path.join(SRC, "ui", name), os.path.join(OUT, "ui", name))

    sys.path.insert(0, os.path.join(KODI, "tools"))
    import render_assets as ra
    import render_ui as ru
    ra.OUT = OUT
    for name, cp in ICONS.items():
        ra.icon(name, cp)

    # profile pictures: the JStationX orbs, plus a USCL one as the default
    ru.OUT = os.path.join(OUT, "avatars")
    os.makedirs(ru.OUT, exist_ok=True)
    ru.user_orb(text="USCL").save(os.path.join(ru.OUT, "uscl.png"))
    for name, cp, top, deep in [
        ("controller", 0xE30F, (0x7c, 0xe0, 0x7a), (0x10, 0x7a, 0x22)),
        ("star", 0xE838, (0xff, 0xd8, 0x5a), (0xc0, 0x6a, 0x00)),
        ("music", 0xE405, (0xff, 0x8a, 0xc8), (0xa8, 0x10, 0x60)),
        ("film", 0xE02C, (0xc2, 0x9a, 0xff), (0x4a, 0x1c, 0xa8)),
        ("bolt", 0xEA0B, (0xff, 0xb0, 0x60), (0xc0, 0x38, 0x00)),
        ("heart", 0xE87D, (0xff, 0x7a, 0x7a), (0xb0, 0x10, 0x18)),
        ("moon", 0xEF44, (0x9a, 0xa8, 0xc8), (0x22, 0x2c, 0x48)),
        ("rocket", 0xEB9B, (0x6a, 0xe8, 0xe0), (0x00, 0x70, 0x80)),
        ("pet", 0xE91D, (0xe0, 0xc0, 0x98), (0x70, 0x48, 0x20)),
    ]:
        ru.user_orb(top=top, deep=deep, glyph_cp=cp).save(os.path.join(ru.OUT, f"{name}.png"))
    shutil.copy(os.path.join(KODI, "third_party", "MaterialIcons-LICENSE.txt"), os.path.join(OUT, "MaterialIcons-LICENSE.txt"))
    print("assets in", OUT)


if __name__ == "__main__":
    main()
