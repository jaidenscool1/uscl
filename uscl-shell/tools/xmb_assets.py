#!/usr/bin/env python3
"""Bring the JStationX XMB artwork into uscl-shell/xmb/.

All of it is generated by the player's kodi-xmb project (no Sony assets): the silk background layers
(bg_lab.py), Material Icons glyphs with the XMB glow (render_assets.py, Apache-2.0 icons) and the UI pieces
(render_ui.py). This copies what the home screen uses and renders the few icons and avatars USCL adds,
with the same functions so they match.

usage: KODI_XMB=~/src/kodi-xmb python3 -I uscl-shell/tools/xmb_assets.py
"""
